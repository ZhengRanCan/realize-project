'use strict';
const assert = require('node:assert/strict');
const { projectTopic } = require('../app/shared/l1-topic-projection');
const map = { topics: [{ id: 'T-1', title: 'T', proposition: 'p', blockIds: [] }], elements: [{ id: 'A', label: 'A', topics: ['T-1'] }, { id: 'B', label: 'B', topics: [] }], edges: [{ id: 'i', from: 'A', to: 'A', type: 'contains' }, { id: 'o', from: 'A', to: 'B', type: 'produces' }, { id: 'r', from: 'B', to: 'A', type: 'relates-to' }] };
const view = projectTopic(map, 'T-1');
assert.equal(view.inside.length, 1); assert.deepEqual(view.relations.map((r) => r.role), ['internal', 'outbound', 'crossing']); assert.equal(view.blockOrganization.state, 'empty');
assert.deepEqual(view.relationClasses.inbound, []); assert.deepEqual(view.relationClasses.outbound, ['o']);
const absent = projectTopic({ ...map, topics: [{ id: 'T-1', title: 'T', proposition: 'p' }] }, 'T-1'); assert.equal(absent.blockOrganization.state, 'unknown');
const empty = projectTopic({ ...map, edges: [] }, 'T-1'); assert.equal(empty.representation, 'boundary-summary');
const fs = require('node:fs');
const main = fs.readFileSync(require.resolve('../app/main/main.js'), 'utf8'); const renderer = fs.readFileSync(require.resolve('../app/renderer/app.js'), 'utf8'); const l0 = fs.readFileSync(require.resolve('../app/renderer/l0-map.js'), 'utf8');
assert.match(main, /l1Topics/); assert.match(renderer, /function viewL1/); assert.match(renderer, /onTopic:/); assert.match(l0, /opts\.onTopic/);
const gold = JSON.parse(fs.readFileSync('samples/context-consumption/framework-map.json', 'utf8'));
const crossing = projectTopic(gold, 'T-03');
assert.deepEqual(crossing.inside.map(e => e.id), ['E-03', 'E-08']);
assert.deepEqual(crossing.outside.map(e => e.id), ['E-02', 'E-04']);
assert.equal(crossing.document.title, gold.document.title);
assert.deepEqual(crossing.inside[0].sourceUnitIds, gold.elements[2].sourceUnitIds);
assert.deepEqual(crossing.relations.map(r => [r.from, r.to, r.type, r.role]), [
  ['E-03', 'E-02', 'consumes', 'outbound'], ['E-03', 'E-04', 'produces', 'outbound'],
]);
const rich = structuredClone(map);
rich.document = {id:'D',title:'Document',sourcePath:'source.md',role:'target'};
rich.topics[0].sectionRefs = ['§1'];
rich.elements[0].sectionRefs = ['§1'];
rich.edges[1].label = '<uses>'; rich.edges[1].note = 'original note';
rich.edges[1].qualifiers = {nested:{text:'original'}};
rich.edges.push({id:'back',from:'B',to:'A',type:'controls'});
const before = JSON.stringify(rich), copied = projectTopic(rich, 'T-1');
assert.deepEqual(copied.outside.map(e => e.id), ['B']);
assert.equal(copied.relations[1].label, '<uses>');
assert.equal(copied.relations[1].note, 'original note');
assert.notEqual(copied.relations[1].qualifiers.nested, rich.edges[1].qualifiers.nested);
assert.ok(Object.isFrozen(copied.relations[1].qualifiers.nested));
assert.ok(Object.isFrozen(copied.blockOrganization.ids));
assert.throws(() => {copied.topic.sectionRefs.push('§2');}, TypeError);
assert.equal(JSON.stringify(rich), before);
assert.equal(Object.hasOwn(projectTopic(map,'T-1').inside[0], 'sourceUnitIds'), false);
const noInside = projectTopic({...map, elements:map.elements.map(e=>({...e,topics:[]}))},'T-1');
assert.deepEqual(noInside.inside, []); assert.deepEqual(noInside.outside, []);
assert.equal(noInside.representation, 'boundary-summary');
const onlyCrossing = projectTopic({...map,edges:map.edges.slice(1)},'T-1');
assert.equal(onlyCrossing.representation, 'boundary-map');
assert.deepEqual(onlyCrossing.relationClasses.internal, []);
const multi = {...map, topics:[...map.topics,{id:'T-2',title:'Other',proposition:'p'}],elements:[{...map.elements[0],topics:['T-1','T-2']},map.elements[1]]};
assert.equal(projectTopic(multi,'T-1').inside[0].id, projectTopic(multi,'T-2').inside[0].id);
const known = projectTopic({...map,topics:[{...map.topics[0],blockIds:['O-1']}]},'T-1');
assert.equal(known.blockOrganization.state,'known'); assert.deepEqual(known.blockOrganization.ids,['O-1']);
assert.equal(Object.hasOwn(known,'blockEntries'),false);
console.log('L1 topic projection/runtime: baseline + boundary display, metadata, states and deep purity passed');

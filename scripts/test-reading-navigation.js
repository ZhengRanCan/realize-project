'use strict';
const assert=require('node:assert/strict');
const {createCanonicalReadingResolver,createNavigationStack}=require('../app/shared/reading-navigation');
const resolver=createCanonicalReadingResolver({sessionKey:'a',elementIds:['E-1','E-2'],blockIds:['O-1']});
assert.deepEqual(resolver.resolve({kind:'block',id:'O-1'}).address,{sessionKey:'a',level:'L2',blockId:'O-1',anchor:'#block-O-1'});
assert.equal(resolver.resolve({kind:'element',id:'E-1'}).address.anchor,'#element-E-1');
for(const kind of ['topic','source-unit','review','evidence','fragment'])assert.equal(resolver.resolve({kind,id:'E-1'}).reason,'unsupported');
assert.equal(resolver.resolve({kind:'block',id:'E-1'}).reason,'unknown');
assert.equal(resolver.resolve(null).ok,false);
const stack=createNavigationStack('a');
const frame={address:{sessionKey:'a',level:'L2',topicId:'T-5',blockId:'O-1'},context:{scroll:150,expanded:{'O-1':true}}};
stack.push(frame);frame.context.expanded['O-1']=false;
const copy=stack.snapshot();copy[0].context.scroll=0;
assert.deepEqual(stack.pop().context,{scroll:150,expanded:{'O-1':true}});
assert.equal(stack.pop(),null);
assert.throws(()=>stack.push({address:{sessionKey:'b',level:'L0'},context:{}}),/session/);
assert.throws(()=>stack.push({address:{sessionKey:'a',level:'L3'},context:{}}),/block/);
stack.push(frame);stack.reset('b');assert.equal(stack.size,0);assert.throws(()=>stack.push(frame),/session/);
console.log('Reading navigation: typed resolver, unique landings, immutable frames, session and empty stack passed');
